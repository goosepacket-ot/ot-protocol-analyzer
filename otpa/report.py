"""Report writers: Markdown, self-contained HTML, JSON and CSV."""
from __future__ import annotations

import csv
import html
import json
import os

SEV_COLOR = {"high": "#c0392b", "medium": "#d68910", "low": "#2874a6", "info": "#5d6d7e"}


def write_all(res: dict, out_dir: str) -> list[str]:
    os.makedirs(out_dir, exist_ok=True)
    paths = []
    p = os.path.join(out_dir, "report.json")
    with open(p, "w", encoding="utf-8") as f:
        json.dump(res, f, indent=2)
    paths.append(p)
    for name, rows, cols in (("assets.csv", res["assets"], ["ip", "mac", "vendor", "name", "roles", "protocols", "vlans", "packets"]),
                             ("flows.csv", res["flows"], ["client", "server", "protocol", "events", "operations"]),
                             ("findings.csv", res["findings"], ["severity", "title", "proto", "source", "target", "count", "example", "advice"])):
        p = os.path.join(out_dir, name)
        with open(p, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(cols)
            for r in rows:
                w.writerow(["; ".join(map(str, v)) if isinstance(v, list) else
                            "; ".join(f"{k}={n}" for k, n in v.items()) if isinstance(v, dict) else v
                            for v in (r.get(c, "") for c in cols)])
        paths.append(p)
    p = os.path.join(out_dir, "report.md")
    with open(p, "w", encoding="utf-8") as f:
        f.write(markdown(res))
    paths.append(p)
    p = os.path.join(out_dir, "report.html")
    with open(p, "w", encoding="utf-8") as f:
        f.write(html_report(res))
    paths.append(p)
    return paths


def _ops(o: dict) -> str:
    return ", ".join(f"{k} {v}" for k, v in o.items())


def markdown(res: dict) -> str:
    s = res["summary"]
    L = [f"# OT traffic assessment — {os.path.basename(res['source']) or 'capture'}", "",
         f"- Packets: **{s['packets']}** over {s['duration_s']} s",
         f"- Assets: **{s['assets']}**, flows: **{s['flows']}**",
         "- Findings: " + (", ".join(f"**{v} {k}**" for k, v in s["findings"].items()) or "none"), "",
         "## Protocols seen", "", "| Protocol | Events |", "|---|---:|"]
    L += [f"| {k} | {v} |" for k, v in s["protocols"].items()]
    L += ["", "## Findings", ""]
    if not res["findings"]:
        L.append("No findings.")
    for i, f in enumerate(res["findings"], 1):
        L += [f"### {i}. [{f['severity'].upper()}] {f['title']}",
              f"- Protocol: {f['proto']} — `{f['source']}` → `{f['target']}` ({f['count']}×)",
              f"- Example: {f['example']}" if f["example"] else "",
              f"- Recommendation: {f['advice']}" if f["advice"] else "", ""]
    L += ["## Asset inventory", "", "| IP | MAC | Vendor | Name | Roles | Protocols | VLAN |", "|---|---|---|---|---|---|---|"]
    for a in res["assets"]:
        L.append(f"| {a['ip']} | {a['mac']} | {a['vendor']} | {a['name']} | {'; '.join(a['roles'])} | "
                 f"{', '.join(a['protocols'])} | {', '.join(map(str, a['vlans']))} |")
    L += ["", "## Communication matrix", "", "| Client | Server | Protocol | Events | Operations |", "|---|---|---|---:|---|"]
    for fl in res["flows"]:
        L.append(f"| {fl['client']} | {fl['server']} | {fl['protocol']} | {fl['events']} | {_ops(fl['operations'])} |")
    L += ["", "_Generated by ot-protocol-analyzer. Passive analysis only — verify findings against the site's "
              "approved communication baseline before acting._", ""]
    return "\n".join(x for x in L if x is not None)


def html_report(res: dict) -> str:
    e = html.escape
    s = res["summary"]
    cards = "".join(f'<div class="card"><b>{v}</b><span>{k}</span></div>' for k, v in
                    (("packets", s["packets"]), ("assets", s["assets"]), ("flows", s["flows"]),
                     ("findings", sum(s["findings"].values()))))
    sev = "".join(f'<span class="pill" style="background:{SEV_COLOR.get(k)}">{v} {k}</span>' for k, v in s["findings"].items())
    protos = "".join(f"<tr><td>{e(k)}</td><td class=n>{v}</td></tr>" for k, v in s["protocols"].items())
    fnd = "".join(
        f'<tr><td><span class="pill" style="background:{SEV_COLOR.get(f["severity"])}">{e(f["severity"])}</span></td>'
        f'<td><b>{e(f["title"])}</b><div class=sub>{e(f["example"])}</div><div class=adv>{e(f["advice"])}</div></td>'
        f'<td>{e(f["proto"])}</td><td><code>{e(f["source"])}</code> → <code>{e(f["target"])}</code></td><td class=n>{f["count"]}</td></tr>'
        for f in res["findings"]) or "<tr><td colspan=5>No findings.</td></tr>"
    ast = "".join(
        f"<tr><td>{e(a['ip'])}</td><td><code>{e(a['mac'])}</code></td><td>{e(a['vendor'])}</td><td>{e(a['name'])}</td>"
        f"<td>{e('; '.join(a['roles']))}</td><td>{e(', '.join(a['protocols']))}</td><td>{e(', '.join(map(str, a['vlans'])))}</td></tr>"
        for a in res["assets"])
    flw = "".join(
        f"<tr><td><code>{e(f['client'])}</code></td><td><code>{e(f['server'])}</code></td><td>{e(f['protocol'])}</td>"
        f"<td class=n>{f['events']}</td><td>{e(_ops(f['operations']))}</td></tr>" for f in res["flows"])
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>OT traffic assessment</title><style>
:root{{--bg:#f6f7f9;--fg:#1c2833;--card:#fff;--line:#e3e6ea;--mut:#5d6d7e}}
@media (prefers-color-scheme:dark){{:root{{--bg:#12161b;--fg:#e6e9ed;--card:#1b2128;--line:#2c343d;--mut:#9aa5b1}}}}
body{{margin:0;font:14px/1.45 system-ui,Segoe UI,sans-serif;background:var(--bg);color:var(--fg)}}
main{{max-width:1200px;margin:auto;padding:24px 16px}}h1{{font-size:22px}}h2{{margin-top:32px;font-size:17px}}
.cards{{display:flex;gap:12px;flex-wrap:wrap}}.card{{background:var(--card);border:1px solid var(--line);border-radius:8px;padding:12px 18px}}
.card b{{display:block;font-size:22px}}.card span{{color:var(--mut)}}
.wrap{{overflow-x:auto}}table{{border-collapse:collapse;width:100%;background:var(--card)}}
td,th{{border-bottom:1px solid var(--line);padding:6px 8px;text-align:left;vertical-align:top}}th{{color:var(--mut);font-weight:600}}
.n{{text-align:right}}.pill{{color:#fff;border-radius:10px;padding:1px 8px;font-size:12px;margin-right:4px;white-space:nowrap}}
.sub{{color:var(--mut);font-size:12px}}.adv{{font-size:12px;margin-top:3px}}code{{font-size:12px}}
</style></head><body><main>
<h1>OT traffic assessment — {e(os.path.basename(res['source']) or 'capture')}</h1>
<div class="cards">{cards}</div><p>{sev}</p>
<h2>Findings</h2><div class=wrap><table><tr><th>Severity</th><th>Finding</th><th>Protocol</th><th>Source → target</th><th>Count</th></tr>{fnd}</table></div>
<h2>Asset inventory</h2><div class=wrap><table><tr><th>IP</th><th>MAC</th><th>Vendor</th><th>Name</th><th>Roles</th><th>Protocols</th><th>VLAN</th></tr>{ast}</table></div>
<h2>Communication matrix</h2><div class=wrap><table><tr><th>Client</th><th>Server</th><th>Protocol</th><th>Events</th><th>Operations</th></tr>{flw}</table></div>
<h2>Protocols</h2><div class=wrap><table><tr><th>Protocol</th><th>Events</th></tr>{protos}</table></div>
<p class=sub>Generated by ot-protocol-analyzer. Passive analysis only — verify findings against the site's approved communication baseline.</p>
</main></body></html>"""
